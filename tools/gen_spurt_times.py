# Writes spurt_times.psc: the ParticleSpurtTimes() table pasted into CS2GameScript.psc.
from nifkeys import parse, keys
import sys
# argv[1]: the Cumshot mod's meshes/Cumshot folder
M = sys.argv[1].rstrip("/\\") + "/"

def starts(path):
    return [tm for k, t, d in parse(path)[0] if t == 'NiBoolData' for (tm, v) in keys(t, d)[1] if v == 1]

out = ["; Start times (seconds after equip) of the spurts in Particles01..15 (index 0..14).",
       "; Read from the emitter-active keys (NiBoolData) of the meshes; SOS and Static meshes share them.",
       r"; Generated by tools\gen_spurt_times.py - regenerate if the particle meshes change.",
       "Float[] Function ParticleSpurtTimes(Int pIndex)", "\tFloat[] t"]
for n in range(1, 16):
    on = starts(M + 'Particles%02dSOS.nif' % n)
    assert on == starts(M + 'Particles%02dStatic.nif' % n)
    out.append("\t%s pIndex == %d" % ("If" if n == 1 else "ElseIf", n - 1))
    out.append("\t\tt = new Float[%d]" % len(on))
    out += ["\t\tt[%d] = %s" % (i, repr(float(tm))) for i, tm in enumerate(on)]
out += ["\tEndIf", "\tReturn t", "EndFunction", ""]
open('spurt_times.psc', 'w').write("\n".join(out))
